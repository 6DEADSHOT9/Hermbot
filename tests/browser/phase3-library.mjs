import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';

const browser=await chromium.launch({headless:true});
const context=await browser.newContext({baseURL:process.env.HERMBOT_TEST_URL||'http://api:8000',viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const nonce=Date.now(),filename=`phase3-input-${nonce}.csv`,output=`phase3-result-${nonce}.md`;
await page.goto(process.env.HERMBOT_TEST_URL||'http://api:8000');
await page.getByLabel('Owner token').fill(process.env.OWNER_TOKEN);
await page.getByRole('button',{name:'Open workspace'}).click();
await page.getByRole('navigation',{name:'Team conversations'}).getByRole('button',{name:/Scout/}).click();
await page.getByLabel('Owner menu').click();await page.getByRole('button',{name:'File library',exact:true}).click();
await page.getByLabel('Upload library file').setInputFiles({name:filename,mimeType:'text/csv',buffer:Buffer.from('Item,Amount\nFirst,3\nSecond,39\n')});
const dialog=page.getByRole('dialog');
await dialog.getByRole('heading',{name:filename,exact:true}).waitFor();
assert.ok((await dialog.locator('table').innerText()).includes('39'));
await dialog.getByRole('button',{name:'Add new version'}).click();
await page.getByLabel('Upload new version').setInputFiles({name:filename,mimeType:'text/csv',buffer:Buffer.from('Item,Amount\nFirst,4\nSecond,38\n')});
await page.waitForFunction(()=>document.querySelector('.library-provenance')?.textContent.includes('Version 2'));
const options=await page.getByLabel('File version').locator('option').all();
assert.equal(options.length,2);
const oldId=await options[1].getAttribute('value'),newId=await options[0].getAttribute('value');
await page.getByLabel('File version').selectOption(oldId);
await page.waitForFunction(()=>document.querySelector('table')?.textContent.includes('39'));
await page.getByLabel('File version').selectOption(newId);
await page.waitForFunction(()=>document.querySelector('table')?.textContent.includes('38'));
await dialog.getByRole('button',{name:'Use in this conversation'}).click();
await dialog.waitFor({state:'hidden'});
assert.ok((await page.locator('.attachment-chips').innerText()).includes(filename));
await page.getByLabel('Message your teammate').fill(`Your first tool call must read the granted CSV ${filename} using read_file. Calculate the total of its Amount column. Then call hermbot_publish exactly twice with the same filename ${output} and content_type text/markdown: first publish a draft containing PHASE3_DRAFT and the computed total, then publish a corrected final containing PHASE3_FINAL and the computed total. These are two immutable versions of one output. Finish with hermbot_finish containing PHASE3_FINAL and the total. Do not delegate, change settings, run external commands or access external services.`);
const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/v1/tasks')&&r.request().method()==='POST');
await page.getByRole('button',{name:'Send message',exact:true}).click();
const created=await (await responsePromise).json();
let task;
for(let i=0;i<150;i++){
  task=await (await context.request.get(`/api/v1/tasks/${created.id}`)).json();
  if(['completed','failed','cancelled','interrupted','uncertain'].includes(task.status))break;
  await page.waitForTimeout(1500);
}
assert.equal(task.status,'completed',JSON.stringify({status:task.status,error:task.error}));
assert.ok(task.output.includes('42')&&task.output.includes('PHASE3_FINAL'));
assert.ok(task.events.some(e=>e.kind==='tool.started'&&e.data.tool==='read_file'));
await page.getByLabel('Owner menu').click();await page.getByRole('button',{name:'File library',exact:true}).click();
await page.getByLabel('Search library').fill(output);
await dialog.locator('.artifact-card').first().click();
await dialog.getByRole('heading',{name:output,exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelector('.library-provenance')?.textContent.includes('Version 2'));
assert.ok((await dialog.locator('.artifact-preview').innerText()).includes('PHASE3_FINAL'));
assert.equal(await page.getByLabel('File version').locator('option').count(),2);
await page.getByLabel('File version').selectOption({index:1});
await page.waitForFunction(()=>document.querySelector('.artifact-preview')?.textContent.includes('PHASE3_DRAFT'));
await dialog.getByRole('button',{name:'Files',exact:true}).click();
await page.getByLabel('Import link URL').fill('https://example.com/');
await dialog.getByRole('button',{name:'Import link',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.library-provenance')?.textContent.includes('link'));
assert.ok((await dialog.locator('.artifact-preview').innerText()).includes('Example Domain'));
await page.screenshot({path:'/output/phase3-library-desktop.png',fullPage:true});
await dialog.getByRole('button',{name:'Search prior work',exact:true}).click();
await page.getByLabel('Search prior work',{exact:true}).fill('PHASE3_FINAL');
await dialog.locator('.history-results .artifact-card').first().waitFor();
assert.ok((await dialog.locator('.history-results').innerText()).includes('PHASE3_FINAL'));
await dialog.getByRole('button',{name:'Close',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await page.getByLabel('Close work panel').click();
await page.getByLabel('Open navigation').click();
await page.getByLabel('Owner menu').click();await page.getByRole('button',{name:'File library',exact:true}).click();
await page.getByLabel('Search library').fill(filename);
await page.getByRole('dialog').locator('.artifact-card').first().click();
await page.getByRole('dialog').getByRole('heading',{name:filename,exact:true}).waitFor();
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'/output/phase3-library-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
await writeFile('/output/phase3-library.json',JSON.stringify({check:'real UI upload, table preview, immutable version history, explicit file grant, native file read, two real output versions, public link ingestion, prior-work search and mobile preview',task_id:created.id,filename,output,version_count:2,script_errors:errors,status:task.status},null,2));
console.log('Phase 3 library UI and real-model versioned output acceptance passed.');
await browser.close();
