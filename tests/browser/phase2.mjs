import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';

const browser=await chromium.launch({headless:true});
const baseURL=process.env.HERMBOT_TEST_URL||'http://api:8000';
const errors=[];
let context=await browser.newContext({viewport:{width:1440,height:1000}});
let page=await context.newPage();
page.on('pageerror',error=>errors.push(error.message));
async function login(){await page.goto(baseURL);await page.getByLabel('Owner token').fill(process.env.OWNER_TOKEN);await page.getByRole('button',{name:'Open workspace'}).click();await page.getByRole('navigation',{name:'Team conversations'}).waitFor();}
async function state(){return page.evaluate(async()=>{const r=await fetch('/api/v1/state');if(!r.ok)throw Error('State unavailable');return r.json();});}
async function until(test,timeout=360000){const end=Date.now()+timeout;while(Date.now()<end){const s=await state();const value=test(s);if(value)return value;await page.waitForTimeout(1000);}throw Error('Acceptance condition timed out');}
await login();
assert.equal((await state()).protocol_fixture,false);
await page.getByRole('button',{name:'Create teammate',exact:true}).click();
await page.getByLabel('Teammate name').fill('Phase 2 UI manager');
await page.getByLabel('Teammate role').fill('You coordinate concise local work. Follow explicit management scope and propose lifecycle changes for owner review.');
await page.getByLabel('Teammate avatar').fill('🧭');
await page.getByLabel('Teammate memory limit').selectOption('1024');
await page.getByLabel('Teammate CPU limit').fill('1');
await page.getByRole('dialog').getByRole('button',{name:'Create teammate',exact:true}).click();
const manager=await until(s=>s.bots.find(b=>b.name==='Phase 2 UI manager'&&b.readiness.compatible));
await page.getByLabel('Owner menu').click();await page.getByRole('button',{name:'Workspace settings',exact:true}).click();
const settings=page.getByRole('dialog');
await settings.getByRole('button',{name:'Providers',exact:true}).click();
assert.ok(await settings.getByText(/permitted models · key configured/).count());
await settings.getByRole('button',{name:'Grants',exact:true}).click();
await page.getByLabel('Grant manager').selectOption(manager.id);
await settings.getByLabel('create (owner approval required)',{exact:true}).check();
await settings.getByRole('button',{name:'Create standing grant',exact:true}).click();
const grant=await until(s=>s.grants.find(g=>g.manager_id===manager.id&&g.kind==='standing'));
await settings.getByRole('button',{name:'Close',exact:true}).click();
await page.getByRole('navigation',{name:'Team conversations'}).getByRole('button',{name:/Phase 2 UI manager/}).click();
await page.getByLabel('Management grant').selectOption(grant.id);
const prompt='Phase 2 UI exit proof: first inspect your owner-issued grant. Propose creation of a new teammate named Phase 2 UI specialist, role: verify small arithmetic using local Python and publish evidence, enabled_tools file and terminal, memory_mb 1024, cpus 1, using the workspace default provider/model. Use hermbot_propose and end your turn for exact owner approval. Once resumed after provisioning, discover the new bot ID, delegate verification that 17 + 25 equals 42 and require a published text artifact containing SPECIALIST_PROOF_42. Yield while it works. Then combine its actual result and publish a final markdown artifact containing PHASE2_WEB_EXIT_42 and the specialist artifact ID. Finish. Do not browse or use external services.';
await page.getByRole('textbox',{name:/Message/}).fill(prompt);
await page.getByRole('button',{name:'Send message',exact:true}).click();
const task=await until(s=>s.tasks.find(t=>t.bot_id===manager.id&&t.input===prompt));
const approval=await until(s=>s.approvals.find(a=>a.task_id===task.id&&a.kind==='lifecycle'&&a.status==='pending'));
const card=page.locator('.review-card').filter({hasText:'Review teammate changes'});
await card.waitFor({timeout:15000});
assert.equal(approval.payload.action,'create');
assert.equal(approval.payload.configuration.name,'Phase 2 UI specialist');
assert.equal(approval.payload.resources.memory_mb,1024);
await page.screenshot({path:'/output/phase2-approval.png',fullPage:true});
await card.getByRole('button',{name:'Allow once',exact:true}).click();
const completed=await until(s=>{const t=s.tasks.find(t=>t.id===task.id);if(['failed','uncertain','cancelled','interrupted'].includes(t?.status))throw Error(`Manager ended ${t.status}: ${t.error}`);return t?.status==='completed'&&t;},480000);
assert.ok(completed.handoffs>=1);
const before=await state();
const child=before.tasks.find(t=>t.parent_id===task.id);
assert.equal(child.status,'completed');
const specialist=before.bots.find(b=>b.id===child.bot_id);
assert.equal(specialist.name,'Phase 2 UI specialist');
const artifacts=before.artifacts.filter(a=>a.task_id===task.id||a.task_id===child.id);
assert.ok(artifacts.length>=2);
await page.getByRole('button',{name:/^Outputs/}).click();
await page.locator('.artifact-card').first().click();
await page.getByRole('dialog').waitFor();
assert.ok((await page.locator('.artifact-preview').innerText()).length>0);
await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
await page.screenshot({path:'/output/phase2-desktop.png',fullPage:true});
await context.close();
context=await browser.newContext({viewport:{width:390,height:844}});
page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
await login();
await page.getByRole('button',{name:'Open navigation'}).click();
await page.getByRole('navigation',{name:'Team conversations'}).getByRole('button',{name:/Phase 2 UI manager/}).click();
await page.waitForTimeout(1000);
assert.equal((await state()).tasks.find(t=>t.id===task.id).status,'completed');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'/output/phase2-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
await writeFile('/output/phase2-browser.json',JSON.stringify({check:'owner creates manager in UI, grants lifecycle responsibility, approves exact specialist proposal, receives real collaborative artifacts and reconnects on mobile',real_model:true,manager_bot_id:manager.id,specialist_bot_id:specialist.id,grant_id:grant.id,approval_id:approval.id,task_id:task.id,child_task_id:child.id,artifacts:artifacts.map(a=>({id:a.id,name:a.name,sha256:a.sha256})),script_errors:errors},null,2));
console.log(JSON.stringify({check:'Phase 2 web exit',task_id:task.id,status:completed.status,handoffs:completed.handoffs,artifacts:artifacts.length}));
await browser.close();
