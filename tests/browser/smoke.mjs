import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(process.env.HERMBOT_TEST_URL || 'http://api:8000');
await page.getByLabel('Owner token').fill(process.env.OWNER_TOKEN);
await page.getByRole('button',{name:'Open workspace'}).click();
await page.getByRole('navigation',{name:'Team conversations'}).waitFor();
assert.equal(await page.getByRole('navigation',{name:'Team conversations'}).getByRole('button').count(),3);
await page.getByRole('button',{name:'New group conversation'}).click();
await page.getByLabel('Conversation name').fill('Browser verified group');
await page.getByRole('button',{name:'Create conversation',exact:true}).click();
await page.getByRole('heading',{name:'Browser verified group',exact:true}).waitFor();
await page.locator('.target-picker select').selectOption('reviewer');
await page.getByRole('button',{name:'Coordinate the team',exact:false}).click();
assert.equal(await page.getByLabel('Coordinate team',{exact:true}).isChecked(),true);
await page.getByLabel('Message your teammate').fill('[POC:manager] Coordinate the evidence and report.');
await page.getByRole('button',{name:'Send message',exact:true}).click();
await page.locator('.task-card').first().waitFor();
await page.getByText('Sage is coordinating',{exact:false}).count();
await page.screenshot({path:'/output/desktop.png',fullPage:true});
await page.getByLabel('Owner menu').click();await page.getByRole('button',{name:'Switch to dark theme'}).click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Close work panel'}).click();
await page.getByRole('button',{name:'Open navigation'}).click();
await page.getByRole('navigation',{name:'Team conversations'}).getByRole('button').first().click();
await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
await page.screenshot({path:'/output/mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
assert.deepEqual(errors,[]);
console.log('Browser login, roster, group, task submission, theme and mobile navigation passed.');
await browser.close();
