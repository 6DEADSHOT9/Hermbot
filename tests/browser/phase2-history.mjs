import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';

const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.HERMBOT_TEST_URL||'http://api:8000');
await page.getByLabel('Owner token').fill(process.env.OWNER_TOKEN);
await page.getByRole('button',{name:'Open workspace'}).click();
const history=page.getByRole('navigation',{name:'Archived conversations'});
await page.getByRole('button',{name:'Past teammates',exact:true}).click();
await history.waitFor();
await history.getByRole('button',{name:/Phase 2 clone proof/}).last().click();
await page.getByRole('heading',{name:'Phase 2 clone proof',exact:true}).waitFor();
await page.getByLabel('Message your teammate').fill('Read-only history stays read-only');
assert.equal(await page.getByRole('button',{name:'Send message',exact:true}).isEnabled(),false);
assert.equal(await page.getByRole('button',{name:'Edit Phase 2 clone proof',exact:true}).count(),0);
await page.getByRole('button',{name:/^Outputs/}).click();
await page.locator('.artifact-card').first().click();
await page.getByRole('dialog').waitFor();
assert.ok((await page.locator('.artifact-preview').innerText()).includes('CLONE_VERIFIED_42'));
await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
await page.screenshot({path:'/output/phase2-retired-history.png',fullPage:true});
assert.deepEqual(errors,[]);
await writeFile('/output/phase2-history.json',JSON.stringify({check:'deleted teammate retains owner-readable permanent conversation and artifact; new work and configuration remain disabled',script_errors:errors},null,2));
console.log('Deleted teammate history, artifact access and read-only controls passed.');
await browser.close();
