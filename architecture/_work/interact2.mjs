import { createRequire } from 'module';
const ROOT = new URL('../../', import.meta.url).pathname;
const require = createRequire(ROOT + 'tests/browser/package.json');
const { chromium } = require('playwright');
const file = 'file://' + ROOT + 'architecture/index.html';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.setDefaultTimeout(8000);
const errs = []; page.on('pageerror', e => errs.push(e.message));
const log = (k, v) => console.log(k.padEnd(34), JSON.stringify(v));
await page.goto(file); await page.waitForTimeout(1500);
log('default view', await page.textContent('#vtitle'));
await page.click('.diagram g[data-node="svc:supervisor"]'); await page.waitForTimeout(500);
log('diagram click opens', await page.textContent('#pbody h2'));
log('plain block on supervisor?', await page.evaluate(() => !!document.querySelector('#pbody .plain')));
await page.click('[data-go="deploy"]'); await page.waitForTimeout(1800);
log('reading-order button ->', await page.textContent('#vtitle'));
await page.goto(file + '#glossary'); await page.waitForTimeout(800);
await page.fill('#gq', 'outbox'); await page.waitForTimeout(200);
log('glossary visible after filter', await page.evaluate(() => [...document.querySelectorAll('.gloss .term')].filter(d => !d.hidden).map(d => d.querySelector('b').textContent)));
await page.goto(file + '#backend'); await page.waitForTimeout(1800);
log('summary edges', await page.evaluate(() => window.__cy.edges('.summary').length));
await page.evaluate(() => window.__cy.edges('.summary')[0].emit('tap') && null); await page.waitForTimeout(400);
log('summary panel', await page.evaluate(() => document.querySelector('#pbody h2').textContent + ' / ' + document.querySelectorAll('#pbody ul.items li').length + ' links'));
await page.check('#showall'); log('show all links visible', await page.evaluate(() => window.__cy.edges('.detail').filter(e => e.visible()).length));
await page.evaluate(() => window.__cy.nodes('.zone')[0].emit('tap') && null); await page.waitForTimeout(500);
log('zone tap zoom', await page.evaluate(() => window.__cy.zoom().toFixed(2)));
await page.goto(file + '#flows'); await page.waitForTimeout(1500);
log('plain step text', await page.textContent('.steptext'));
log('technical detail present', await page.isVisible('.tech summary'));
console.log('-> sms'); await page.goto(file + '#sms'); await page.waitForTimeout(1200); console.log('-> click'); await page.click('[data-side="sm:task"]'); await page.waitForTimeout(800); console.log('-> tap');
await page.evaluate(() => window.__cy.nodes()[0].emit('tap') && null); await page.waitForTimeout(300);
log('state plain meaning', await page.evaluate(() => (document.querySelector('#pbody .plain') || {}).textContent));
await page.goto(file + '#disc'); await page.waitForTimeout(1200);
const did = await page.evaluate(() => MODEL.nodes.find(n => n.kind === 'discrepancy' && n.facts.severity === 'high').id);
await page.evaluate(id => window.__cy.getElementById(id).emit('tap') && null, did); await page.waitForTimeout(300);
log('discrepancy plain', await page.evaluate(() => (document.querySelector('#pbody .plain') || {}).textContent.slice(0, 160)));
log('errors', errs);
await browser.close();
