import { createRequire } from 'module';
const ROOT = new URL('../../', import.meta.url).pathname;
const require = createRequire(ROOT + 'tests/browser/package.json');
const { chromium } = require('playwright');
const file = 'file://' + ROOT + 'architecture/index.html';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const log = (k, v) => console.log(k.padEnd(34), JSON.stringify(v));
await page.goto(file + '#backend'); await page.waitForTimeout(2000);
// click a node via cytoscape API
await page.evaluate(() => { const n = window.__cy?.nodes('[kind="module"]')[0]; n && n.emit('tap'); });
log('panel open after node tap', await page.evaluate(() => !document.getElementById('main').classList.contains('nopanel') && document.querySelector('#pbody h2')?.textContent));
await page.click('#filterbtn'); log('filters visible', await page.isVisible('#filters'));
await page.click('[data-mode="hide"]'); log('hide mode active', await page.evaluate(() => document.querySelector('[data-mode="hide"]').classList.contains('on')));
await page.click('#legendbtn'); log('legend visible', await page.isVisible('#legend'));
await page.keyboard.press('Escape'); log('esc closes popovers', !(await page.isVisible('#legend')));
await page.click('[data-focus]'); await page.waitForTimeout(1500); log('focus view', await page.textContent('#vtitle'));
log('focus nodes', await page.evaluate(() => window.__cy.nodes().length));
log('hash', await page.evaluate(() => location.hash));
const h = await page.evaluate(() => location.hash);
await page.goto('about:blank'); await page.goto(file + h); await page.waitForTimeout(2000);
log('hash restore title', await page.textContent('#vtitle'));
log('hash restore panel', await page.evaluate(() => document.querySelector('#pbody h2')?.textContent));
await page.keyboard.press('/'); log('slash focuses search', await page.evaluate(() => document.activeElement.id));
await page.keyboard.type('hermbot_finish'); await page.waitForTimeout(300); log('search results', await page.evaluate(() => document.querySelectorAll('#results [data-res]').length));
await page.keyboard.press('Enter'); await page.waitForTimeout(1800); log('search jump panel', await page.evaluate(() => document.querySelector('#pbody h2')?.textContent));
await page.goto(file + '#features'); await page.waitForTimeout(1500);
await page.evaluate(() => { const n = window.__cy.getElementById('feature:outcomes'); n.emit('tap'); }); await page.waitForTimeout(1800);
log('feature expand title', await page.textContent('#vtitle'));
log('feature panel sections', await page.evaluate(() => [...document.querySelectorAll('#pbody details>summary')].map(s => s.textContent.replace(/\d+$/, '')).slice(0, 14)));
await page.goto(file + '#flows'); await page.waitForTimeout(2000);
await page.click('#snext'); await page.click('#snext'); log('stepper at', await page.textContent('.stepctl b'));
log('active nodes', await page.evaluate(() => window.__cy.nodes('.active').length));
await page.click('[data-side="flow:f"]'); await page.waitForTimeout(1500); log('flow f steps', await page.textContent('.stepctl b'));
await page.goto(file + '#sms'); await page.waitForTimeout(1500); await page.click('[data-side="sm:task"]'); await page.waitForTimeout(1500);
log('sm:task states', await page.evaluate(() => window.__cy.nodes().length));
await page.click('#covbadge'); log('coverage modal', await page.evaluate(() => document.querySelector('#mbody h2')?.textContent + ' / ' + document.querySelectorAll('#mbody tbody tr').length + ' rows'));
await page.keyboard.press('Escape');
await page.click('#themebtn'); log('theme toggled', await page.evaluate(() => document.documentElement.getAttribute('data-theme')));
await page.click('#sdbtn'); log('system design sections', await page.evaluate(() => document.querySelectorAll('#pbody details').length));
await page.goto(file + '#all'); const t0 = Date.now(); await page.waitForFunction(() => window.__cy && window.__cy.nodes().length > 1000, null, {timeout: 30000});
log('full graph nodes / ms', [await page.evaluate(() => window.__cy.nodes().length), Date.now() - t0]);
log('errors', errs);
await browser.close();
